# DRUNet / DPIR (MIT, Copyright 2020 Kai Zhang). Same state-dict layout as
# official UNetRes, nb=4, stride-convolution down / transposed-convolution up.
class DRUResBlock(nn.Module):
    def __init__(self,c):
        super().__init__();self.res=nn.Sequential(nn.Conv2d(c,c,3,padding=1,bias=False),nn.ReLU(),nn.Conv2d(c,c,3,padding=1,bias=False))
    def forward(self,x):return x+self.res(x)

class DRUNet(nn.Module):
    def __init__(self):
        super().__init__()
        self.m_head=nn.Conv2d(4,64,3,padding=1,bias=False)
        for i,(a,b) in enumerate(((64,128),(128,256),(256,512)),1):
            setattr(self,'m_down'+str(i),nn.Sequential(*[DRUResBlock(a) for _ in range(4)],nn.Conv2d(a,b,2,stride=2,bias=False)))
            setattr(self,'m_up'+str(i),nn.Sequential(nn.ConvTranspose2d(b,a,2,stride=2,bias=False),*[DRUResBlock(a) for _ in range(4)]))
        self.m_body=nn.Sequential(*[DRUResBlock(512) for _ in range(4)])
        self.m_tail=nn.Conv2d(64,3,3,padding=1,bias=False)
    def forward(self,image,sigma):
        h,w=image.shape[2:]
        x=torch.cat((image,sigma.expand(image.shape[0],1,h,w)),1)
        x=F.pad(x,(0,(8-w%8)%8,0,(8-h%8)%8),mode='replicate')
        x1=self.m_head(x);x2=self.m_down1(x1);x3=self.m_down2(x2);x4=self.m_down3(x3)
        x=self.m_body(x4);x=self.m_up3(x+x4);x=self.m_up2(x+x3);x=self.m_up1(x+x2)
        return self.m_tail(x+x1)[:,:,:h,:w]




class LayerNorm2d(nn.Module):
    def __init__(self, channels, eps=1e-6):
        super().__init__(); self.weight=nn.Parameter(torch.ones(channels)); self.bias=nn.Parameter(torch.zeros(channels)); self.eps=eps
    def forward(self, x):
        mean=x.mean(1,keepdim=True); variance=(x-mean).pow(2).mean(1,keepdim=True)
        return (x-mean)/torch.sqrt(variance+self.eps)*self.weight[None,:,None,None]+self.bias[None,:,None,None]

class SimpleGate(nn.Module):
    def forward(self, x):
        x1, x2 = x.chunk(2, dim=1)
        return x1 * x2

class NAFBlock(nn.Module):
    def __init__(self, c, DW_Expand=2, FFN_Expand=2, drop_out_rate=0.):
        super().__init__()
        dw_channel = c * DW_Expand
        self.conv1 = nn.Conv2d(in_channels=c, out_channels=dw_channel, kernel_size=1, padding=0, stride=1, groups=1, bias=True)
        self.conv2 = nn.Conv2d(in_channels=dw_channel, out_channels=dw_channel, kernel_size=3, padding=1, stride=1, groups=dw_channel,
                               bias=True)
        self.conv3 = nn.Conv2d(in_channels=dw_channel // 2, out_channels=c, kernel_size=1, padding=0, stride=1, groups=1, bias=True)

        # Simplified Channel Attention
        self.sca = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Conv2d(in_channels=dw_channel // 2, out_channels=dw_channel // 2, kernel_size=1, padding=0, stride=1,
                      groups=1, bias=True),
        )

        # SimpleGate
        self.sg = SimpleGate()

        ffn_channel = FFN_Expand * c
        self.conv4 = nn.Conv2d(in_channels=c, out_channels=ffn_channel, kernel_size=1, padding=0, stride=1, groups=1, bias=True)
        self.conv5 = nn.Conv2d(in_channels=ffn_channel // 2, out_channels=c, kernel_size=1, padding=0, stride=1, groups=1, bias=True)

        self.norm1 = LayerNorm2d(c)
        self.norm2 = LayerNorm2d(c)

        self.dropout1 = nn.Dropout(drop_out_rate) if drop_out_rate > 0. else nn.Identity()
        self.dropout2 = nn.Dropout(drop_out_rate) if drop_out_rate > 0. else nn.Identity()

        self.beta = nn.Parameter(torch.zeros((1, c, 1, 1)), requires_grad=True)
        self.gamma = nn.Parameter(torch.zeros((1, c, 1, 1)), requires_grad=True)

    def forward(self, inp):
        x = inp

        x = self.norm1(x)

        x = self.conv1(x)
        x = self.conv2(x)
        x = self.sg(x)
        x = x * self.sca(x)
        x = self.conv3(x)

        x = self.dropout1(x)

        y = inp + x * self.beta

        x = self.conv4(self.norm2(y))
        x = self.sg(x)
        x = self.conv5(x)

        x = self.dropout2(x)

        return y + x * self.gamma


class NAFNet(nn.Module):

    def __init__(self, img_channel=3, width=16, middle_blk_num=1, enc_blk_nums=[], dec_blk_nums=[]):
        super().__init__()

        self.intro = nn.Conv2d(in_channels=img_channel, out_channels=width, kernel_size=3, padding=1, stride=1, groups=1,
                              bias=True)
        self.ending = nn.Conv2d(in_channels=width, out_channels=img_channel, kernel_size=3, padding=1, stride=1, groups=1,
                              bias=True)

        self.encoders = nn.ModuleList()
        self.decoders = nn.ModuleList()
        self.middle_blks = nn.ModuleList()
        self.ups = nn.ModuleList()
        self.downs = nn.ModuleList()

        chan = width
        for num in enc_blk_nums:
            self.encoders.append(
                nn.Sequential(
                    *[NAFBlock(chan) for _ in range(num)]
                )
            )
            self.downs.append(
                nn.Conv2d(chan, 2*chan, 2, 2)
            )
            chan = chan * 2

        self.middle_blks = \
            nn.Sequential(
                *[NAFBlock(chan) for _ in range(middle_blk_num)]
            )

        for num in dec_blk_nums:
            self.ups.append(
                nn.Sequential(
                    nn.Conv2d(chan, chan * 2, 1, bias=False),
                    nn.PixelShuffle(2)
                )
            )
            chan = chan // 2
            self.decoders.append(
                nn.Sequential(
                    *[NAFBlock(chan) for _ in range(num)]
                )
            )

        self.padder_size = 2 ** len(self.encoders)

    def forward(self, inp):
        B, C, H, W = inp.shape
        inp = self.check_image_size(inp)

        x = self.intro(inp)

        encs = []

        for encoder, down in zip(self.encoders, self.downs):
            x = encoder(x)
            encs.append(x)
            x = down(x)

        x = self.middle_blks(x)

        for decoder, up, enc_skip in zip(self.decoders, self.ups, encs[::-1]):
            x = up(x)
            x = x + enc_skip
            x = decoder(x)

        x = self.ending(x)
        x = x + inp

        return x[:, :, :H, :W]

    def check_image_size(self, x):
        _, _, h, w = x.size()
        mod_pad_h = (self.padder_size - h % self.padder_size) % self.padder_size
        mod_pad_w = (self.padder_size - w % self.padder_size) % self.padder_size
        x = F.pad(x, (0, mod_pad_w, 0, mod_pad_h))
        return x


